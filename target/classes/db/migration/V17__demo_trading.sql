-- Paper trading: an immutable trade log, and nothing else.
--
-- There is deliberately no balance column anywhere. Cash, holdings, average cost and P&L are
-- all folded out of these rows on read, the same way PlayStreak and the badges are: a stored
-- balance is a second source of truth that can drift from the trades that produced it, and the
-- ways it drifts (a partial update, a retried request, a crash between two writes) all look
-- like the player gained or lost money they never traded for.
--
-- demo_accounts holds no money either. It exists for two reasons: it is the row a trade locks
-- so two concurrent buys cannot both pass the same "can they afford it" check, and opened_at is
-- what a reset moves. Resetting rewinds the account without deleting anything — the derivation
-- simply stops looking at trades from before the new mark.
CREATE TABLE demo_accounts (
    user_id   bigint PRIMARY KEY REFERENCES users (id) ON DELETE CASCADE,
    opened_at timestamp(6) with time zone NOT NULL,
    resets    integer NOT NULL DEFAULT 0
);

CREATE TABLE demo_trades (
    id         bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id    bigint NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    asset_id   bigint NOT NULL REFERENCES assets (id),
    side       varchar(8) NOT NULL CHECK (side IN ('BUY', 'SELL')),
    -- Quantity and price are what happened; cost is quantity * price and is not stored, so the
    -- two can never disagree with the third.
    quantity   numeric(30, 10) NOT NULL CHECK (quantity > 0),
    price      numeric(30, 10) NOT NULL CHECK (price > 0),
    fee        numeric(30, 10) NOT NULL CHECK (fee >= 0),
    created_at timestamp(6) with time zone NOT NULL
);

-- Every read is "this account's trades since it was opened, oldest first" — the fold order.
CREATE INDEX idx_demo_trades_user_time ON demo_trades (user_id, created_at);
