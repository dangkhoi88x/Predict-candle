-- Moves the "Blog / Kiến Thức" content out of blog.js and into the database, so editing a
-- post stops meaning editing code and deploying.
--
-- body and tags are jsonb rather than child tables. A post's body is an ordered list of
-- blocks whose shape varies by type ({type:"text",text} / {type:"image",src,w,h,alt}), it is
-- always read and written whole, and nothing queries inside it — three properties that make
-- normalising it work with no payoff. jsonb over json so equality and containment still work
-- if that ever changes.
CREATE TABLE blog_posts (
    id           bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    slug         varchar(180) NOT NULL,
    title        varchar(300) NOT NULL,
    tags         jsonb NOT NULL DEFAULT '[]'::jsonb,
    source       varchar(300),
    source_url   varchar(600),
    image_credit text,
    -- Exactly one of these carries the card illustration: an inline SVG drawn for the post,
    -- or a URL for the ones using an author's own image.
    cover_svg    text,
    cover_img    varchar(600),
    body         jsonb NOT NULL DEFAULT '[]'::jsonb,
    published    boolean NOT NULL DEFAULT false,
    -- Display order on the tab. Not created_at: the order posts are written in is not the
    -- order they should be read in.
    position     integer NOT NULL DEFAULT 0,
    created_at   timestamp(6) with time zone NOT NULL,
    updated_at   timestamp(6) with time zone NOT NULL,
    CONSTRAINT uq_blog_posts_slug UNIQUE (slug)
);

-- The public tab reads published posts in display order and nothing else.
CREATE INDEX idx_blog_posts_published_position ON blog_posts (published, position);
