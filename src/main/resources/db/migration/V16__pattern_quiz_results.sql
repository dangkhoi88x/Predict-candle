-- One answer per player per day for the pattern quiz.
--
-- Its own table rather than a row in guess_results, because the answer is not a direction:
-- those columns are CHECK-constrained to LONG/SHORT and the quiz answers with one of thirteen
-- pattern ids. Shoehorning it in would have meant loosening a constraint that is doing real
-- work for the game it was written for.
--
-- The consequence is deliberate and worth stating: nothing that reads guess_results —
-- PlayerScore, the leaderboard, retention, badges — can see these rows. Naming a pattern and
-- calling a direction are different skills, and one score covering both would say less than
-- either. The day streak is the exception, and it unions this table in: doing the quiz is
-- turning up, which is the only thing that streak claims to measure.
--
-- The unique constraint is what limits the quiz to one attempt a day, the same way the daily
-- challenge's does — there is no "attempted" flag anywhere, the answer is the record of it.
--
-- ON DELETE CASCADE follows live_predictions rather than guess_results: deleting a player has
-- to take these with it, and a cascade cannot be forgotten the way another explicit delete in
-- AdminPlayerService could be.
CREATE TABLE pattern_quiz_results (
    id                 bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id            bigint NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    day                date NOT NULL,
    pattern_id         varchar(64) NOT NULL,
    guessed_pattern_id varchar(64) NOT NULL,
    correct            boolean NOT NULL,
    created_at         timestamp(6) with time zone NOT NULL,
    CONSTRAINT uq_pattern_quiz_results_user_day UNIQUE (user_id, day)
);

-- The day streak reads "which UTC days did this player do anything on", per player.
CREATE INDEX idx_pattern_quiz_results_user_day ON pattern_quiz_results (user_id, day);
