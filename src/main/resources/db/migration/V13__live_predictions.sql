-- One live round is one real candle, and a round is identified by that candle's open time
-- rather than by a row. Nothing here records the round itself: the clock decides which round is
-- open, and the candle that arrives from Binance decides how it ended, so this table only holds
-- what a player called and when.
create table live_predictions (
    id          bigint generated by default as identity primary key,
    user_id     bigint                      not null references users (id) on delete cascade,
    asset_id    bigint                      not null references assets (id) on delete cascade,
    timeframe   varchar(16)                 not null,
    open_time   timestamp(6) with time zone not null,
    direction   varchar(8)                  not null,
    created_at  timestamp(6) with time zone not null
);

-- The whole anti-replay story, same as guess_results: one call per account per round, enforced
-- by the database rather than by a check the application could forget to make.
alter table live_predictions
    add constraint uq_live_prediction_per_round unique (user_id, asset_id, timeframe, open_time);

-- Reading a round means counting both sides of the crowd for one (asset, timeframe, open_time).
create index idx_live_predictions_round on live_predictions (asset_id, timeframe, open_time);

-- And a player's own history is read newest-first.
create index idx_live_predictions_user_time on live_predictions (user_id, open_time desc);
